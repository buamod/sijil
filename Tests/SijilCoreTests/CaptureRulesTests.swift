import Foundation
import Testing

@testable import SijilCore

@Suite("CaptureRules")
struct CaptureRulesTests {
  private let stringType = PasteboardType.string.rawValue
  private let rtfType = PasteboardType.rtf.rawValue
  private let pngType = PasteboardType.png.rawValue
  private let noPatterns = CompiledPatterns([])

  private func rules() -> CaptureRules { CaptureRules() }

  @Test("Ordinary text is captured")
  func capturesText() {
    let rejection = rules().rejection(
      types: [stringType],
      bundleID: "com.apple.Safari",
      text: "hello",
      patterns: noPatterns
    )
    #expect(rejection == nil)
  }

  @Test("Concealed content is refused even with everything else enabled")
  func refusesConcealed() {
    var configuration = rules()
    configuration.ignoredApps = []
    configuration.allowedApps = []
    let rejection = configuration.rejection(
      types: [stringType, PasteboardType.concealed.rawValue],
      bundleID: "com.1password",
      text: "hunter2",
      patterns: noPatterns
    )
    #expect(rejection == .privacyMarker(PasteboardType.concealed.rawValue))
  }

  @Test("Transient and auto-generated markers are also refused")
  func refusesTransientAndAutoGenerated() {
    let configuration = rules()
    for marker in [PasteboardType.transient, .autoGenerated] {
      let rejection = configuration.rejection(
        types: [stringType, marker.rawValue],
        bundleID: nil,
        text: "x",
        patterns: noPatterns
      )
      #expect(rejection == .privacyMarker(marker.rawValue))
    }
  }

  @Test("Privacy markers win over an allowlist")
  func privacyBeatsAllowlist() {
    var configuration = rules()
    configuration.allowedApps = ["com.1password"]
    let rejection = configuration.rejection(
      types: [stringType, PasteboardType.concealed.rawValue],
      bundleID: "com.1password",
      text: "secret",
      patterns: noPatterns
    )
    #expect(rejection == .privacyMarker(PasteboardType.concealed.rawValue))
  }

  @Test("Pausing stops everything")
  func pauseWins() {
    var configuration = rules()
    configuration.isCapturing = false
    let rejection = configuration.rejection(
      types: [stringType],
      bundleID: nil,
      text: "x",
      patterns: noPatterns
    )
    #expect(rejection == .paused)
  }

  @Test("Empty payloads are rejected")
  func rejectsEmpty() {
    let rejection = rules().rejection(
      types: [PasteboardType.appleWebArchive.rawValue],
      bundleID: nil,
      text: nil,
      patterns: noPatterns
    )
    #expect(rejection == .noSubstantiveContent)
  }

  @Test("Universal Clipboard can be skipped")
  func rejectsUniversalClipboard() {
    var configuration = rules()
    configuration.ignoresUniversalClipboard = true
    let rejection = configuration.rejection(
      types: [stringType, PasteboardType.universalClipboard.rawValue],
      bundleID: nil,
      text: "from my phone",
      patterns: noPatterns
    )
    #expect(rejection == .typeIgnored(PasteboardType.universalClipboard.rawValue))

    configuration.ignoresUniversalClipboard = false
    #expect(
      configuration.rejection(
        types: [stringType, PasteboardType.universalClipboard.rawValue],
        bundleID: nil,
        text: "from my phone",
        patterns: noPatterns
      ) == nil
    )
  }

  @Test("Ignored apps are skipped")
  func ignoresApps() {
    var configuration = rules()
    configuration.ignoredApps = ["com.apple.Terminal"]
    #expect(
      configuration.rejection(
        types: [stringType],
        bundleID: "com.apple.Terminal",
        text: "rm -rf /",
        patterns: noPatterns
      ) == .appIgnored("com.apple.Terminal")
    )
  }

  @Test("Allowlist mode inverts the app check")
  func allowlistInverts() {
    var configuration = rules()
    configuration.allowedApps = ["com.apple.Safari"]
    #expect(
      configuration.rejection(
        types: [stringType],
        bundleID: "com.apple.Safari",
        text: "x",
        patterns: noPatterns
      ) == nil
    )
    #expect(
      configuration.rejection(
        types: [stringType],
        bundleID: "com.apple.Mail",
        text: "x",
        patterns: noPatterns
      ) == .notAllowlisted("com.apple.Mail")
    )
  }

  @Test("Ignore patterns drop matching text")
  func patternsDrop() {
    var configuration = rules()
    // Case-insensitive, as password-ish patterns almost always need to be.
    configuration.ignoredPatterns = ["(?i)password"]
    let patterns = CompiledPatterns(configuration.ignoredPatterns)

    #expect(
      configuration.rejection(
        types: [stringType],
        bundleID: nil,
        text: "my Password is hunter2",
        patterns: patterns
      ) == .patternMatched
    )
    #expect(
      configuration.rejection(
        types: [stringType],
        bundleID: nil,
        text: "nothing sensitive",
        patterns: patterns
      ) == nil
    )
  }

  @Test("Invalid patterns are dropped rather than crashing")
  func invalidPatternsAreIgnored() {
    // An unbalanced group must not take the app down at launch.
    let patterns = CompiledPatterns(["([unclosed"])
    #expect(patterns.isEmpty)
  }

  @Test("Image-only copies can be skipped")
  func imageToggle() {
    var configuration = rules()
    configuration.capturesImages = false
    #expect(
      configuration.rejection(
        types: [pngType],
        bundleID: nil,
        text: nil,
        patterns: noPatterns
      ) == .imagesDisabled
    )
    // Text alongside an image still counts as textual.
    #expect(
      configuration.rejection(
        types: [pngType, stringType],
        bundleID: nil,
        text: "caption",
        patterns: noPatterns
      ) == nil
    )
  }

  @Test("Extra ignored types are honoured")
  func extraIgnoredTypes() {
    var configuration = rules()
    configuration.extraIgnoredTypes = ["com.example.secret"]
    #expect(
      configuration.rejection(
        types: [stringType, "com.example.secret"],
        bundleID: nil,
        text: "x",
        patterns: noPatterns
      ) == .typeIgnored("com.example.secret")
    )
  }
}

@Suite("TextSanitizer")
struct TextSanitizerTests {
  @Test("Plain text passes through unchanged")
  func plainTextUnchanged() {
    #expect(TextSanitizer.sanitizeForTitle("hello world") == "hello world")
  }

  @Test("Control characters are stripped")
  func stripsControlCharacters() {
    let sanitized = TextSanitizer.sanitizeForTitle("a\u{0007}b\u{001B}c")
    #expect(sanitized == "abc")
  }

  @Test("Newlines and tabs survive for multiline payloads")
  func keepsWhitespace() {
    #expect(TextSanitizer.sanitizeForTitle("a\nb\tc") == "a\nb\tc")
  }

  @Test("Runaway decoration runs are capped")
  func capsDecorationRuns() {
    // A pathological ZWJ chain is what wedges CoreText on macOS 26.
    let zwj = String(repeating: "\u{200D}", count: 5_000)
    let sanitized = TextSanitizer.sanitizeForTitle("a\(zwj)b")
    #expect(sanitized.count < 100)
  }

  @Test("Legitimate emoji survive")
  func keepsEmoji() {
    #expect(TextSanitizer.sanitizeForTitle("🎉 🇯🇵 👨‍👩‍👧‍👦") == "🎉 🇯🇵 👨‍👩‍👧‍👦")
  }

  @Test("Titles are truncated")
  func truncates() {
    let long = String(repeating: "a", count: 5_000)
    #expect(TextSanitizer.sanitizeForTitle(long).count <= TextSanitizer.maxTitleScalars)
  }

  @Test("Preview collapses whitespace onto one line")
  func previewIsSingleLine() {
    #expect(TextSanitizer.previewLine("a\n\n  b\tc  ") == "a b c")
  }

  @Test("Sanitizing is idempotent")
  func idempotent() {
    let once = TextSanitizer.sanitizeForTitle("x\u{0007}\u{200D}\u{200D}y")
    #expect(TextSanitizer.sanitizeForTitle(once) == once)
  }
}
