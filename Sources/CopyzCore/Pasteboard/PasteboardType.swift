import AppKit

/// Pasteboard type identifiers we care about.
///
/// The three `org.nspasteboard.*` markers are the community convention from
/// nspasteboard.org — they are how an app says "do not record this". There is no
/// Apple constant for them, so they are spelled out here.
public enum PasteboardType: Hashable, Sendable, RawRepresentable, CaseIterable {
  // MARK: Textual
  case string
  case html
  case rtf
  case rtfd
  case fileURL
  case pdf

  // MARK: Images
  case png
  case tiff
  case jpeg
  case heic
  case gif

  // MARK: Privacy markers
  case concealed
  case transient
  case autoGenerated

  // MARK: Noise we deliberately drop
  case appleWebArchive
  case safariWebArchive
  case universalClipboard
  case linkPresentationMetadata
  case webkitCustomData
  case chromiumCustomData
  case chromiumSourceURL
  case notesRichText

  // MARK: Microsoft
  case microsoftLinkSource
  case microsoftObjectLink

  /// Stamped on everything this app writes so we can recognise our own writes
  /// and avoid recording them as fresh history.
  case selfMarker

  /// Failable because the pasteboard carries many types we do not model, and
  /// we need to distinguish "unknown, so leave it alone" from a known type we
  /// can classify.
  public init?(rawValue: String) {
    switch rawValue {
    case NSPasteboard.PasteboardType.string.rawValue: self = .string
    case NSPasteboard.PasteboardType.html.rawValue: self = .html
    case NSPasteboard.PasteboardType.rtf.rawValue: self = .rtf
    case NSPasteboard.PasteboardType.rtfd.rawValue: self = .rtfd
    case NSPasteboard.PasteboardType.fileURL.rawValue: self = .fileURL
    case NSPasteboard.PasteboardType.pdf.rawValue: self = .pdf
    case NSPasteboard.PasteboardType.png.rawValue: self = .png
    case NSPasteboard.PasteboardType.tiff.rawValue: self = .tiff
    case "public.jpeg": self = .jpeg
    case "public.heic": self = .heic
    case "com.compuserve.gif": self = .gif
    case "org.nspasteboard.ConcealedType": self = .concealed
    case "org.nspasteboard.TransientType": self = .transient
    case "org.nspasteboard.AutoGeneratedType": self = .autoGenerated
    case "Apple Web Archive pasteboard type": self = .appleWebArchive
    case "com.apple.webarchive": self = .safariWebArchive
    case "com.apple.is-remote-clipboard": self = .universalClipboard
    case "com.apple.linkpresentation.metadata": self = .linkPresentationMetadata
    case "com.apple.WebKit.custom-pasteboard-data": self = .webkitCustomData
    case "org.chromium.web-custom-data": self = .chromiumCustomData
    case "org.chromium.source-url": self = .chromiumSourceURL
    case "com.apple.notes.richtext": self = .notesRichText
    case "com.microsoft.Link-Source": self = .microsoftLinkSource
    case "com.microsoft.ObjectLink": self = .microsoftObjectLink
    case Self.selfMarker.rawValue: self = .selfMarker
    default: return nil
    }
  }

  public var rawValue: String {
    switch self {
    case .string: NSPasteboard.PasteboardType.string.rawValue
    case .html: NSPasteboard.PasteboardType.html.rawValue
    case .rtf: NSPasteboard.PasteboardType.rtf.rawValue
    case .rtfd: NSPasteboard.PasteboardType.rtfd.rawValue
    case .fileURL: NSPasteboard.PasteboardType.fileURL.rawValue
    case .pdf: NSPasteboard.PasteboardType.pdf.rawValue
    case .png: NSPasteboard.PasteboardType.png.rawValue
    case .tiff: NSPasteboard.PasteboardType.tiff.rawValue
    case .jpeg: "public.jpeg"
    case .heic: "public.heic"
    case .gif: "com.compuserve.gif"
    case .concealed: "org.nspasteboard.ConcealedType"
    case .transient: "org.nspasteboard.TransientType"
    case .autoGenerated: "org.nspasteboard.AutoGeneratedType"
    case .appleWebArchive: "Apple Web Archive pasteboard type"
    case .safariWebArchive: "com.apple.webarchive"
    case .universalClipboard: "com.apple.is-remote-clipboard"
    case .linkPresentationMetadata: "com.apple.linkpresentation.metadata"
    case .webkitCustomData: "com.apple.WebKit.custom-pasteboard-data"
    case .chromiumCustomData: "org.chromium.web-custom-data"
    case .chromiumSourceURL: "org.chromium.source-url"
    case .notesRichText: "com.apple.notes.richtext"
    case .microsoftLinkSource: "com.microsoft.Link-Source"
    case .microsoftObjectLink: "com.microsoft.ObjectLink"
    case .selfMarker: "org.copyz.marker"
    }
  }

  /// Marks that the producing app asked us not to record this copy.
  public static let privacyMarkers: Set<PasteboardType> = [.concealed, .transient, .autoGenerated]

  /// Types carrying image payloads.
  public static let imageKinds: Set<PasteboardType> = [.png, .tiff, .jpeg, .heic, .gif]

  /// Types carrying textual payloads.
  public static let textualKinds: Set<PasteboardType> = [.string, .html, .rtf, .rtfd, .fileURL]

  /// Types that carry user-meaningful payload.
  public static let substantive: Set<PasteboardType> = imageKinds.union(textualKinds)

  /// Types we display if present but never store — web archives are tens of
  /// megabytes of stale page state.
  public static let unpersistable: Set<PasteboardType> = [.appleWebArchive, .safariWebArchive]

  /// Type-name prefixes whose contents are transient engine state.
  public static let droppedPrefixes = ["dyn.", "com.microsoft.ole.source."]

  public static func isPersistable(_ raw: String) -> Bool {
    guard let known = PasteboardType(rawValue: raw) else {
      // Unknown type: persist unless it looks like transient engine state.
      return !droppedPrefixes.contains { raw.hasPrefix($0) }
    }
    return !unpersistable.contains(known)
  }

  public static func isKnown(_ raw: String) -> Bool {
    PasteboardType(rawValue: raw) != nil
  }
}

extension NSPasteboard.PasteboardType {
  /// Bridging shim so AppKit-typed collections can be filtered with our enum.
  public var clipz: PasteboardType? {
    PasteboardType(rawValue: rawValue)
  }
}